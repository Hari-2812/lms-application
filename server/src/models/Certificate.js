const mongoose = require('mongoose');
const crypto = require('crypto');

/**
 * An issued certificate.
 *
 * Two kinds share this collection:
 *   course — generated automatically the moment a student completes every
 *            lesson in a course. Unique per (userId, courseId).
 *   sample — generated on demand from the Certificate section's sample form,
 *            so anyone can see what a finished certificate looks like
 *            without having to complete a course first.
 *
 * The serial is what makes a certificate checkable: it is printed on the
 * certificate face and resolves through GET /api/certificates/verify/:serial.
 */
const certificateSchema = new mongoose.Schema(
  {
    // Absent only for a sample generated by a signed-out visitor.
    userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', index: true },
    courseId: { type: mongoose.Schema.Types.ObjectId, ref: 'Course' },

    kind: { type: String, enum: ['course', 'sample'], default: 'course', index: true },

    // Denormalised on purpose: a certificate is a record of what was true on
    // the day it was issued, so renaming a course later must not rewrite
    // certificates that have already been handed out.
    recipientName: { type: String, required: true },
    courseTitle: { type: String, required: true },
    instructor: { type: String, default: '' },
    lessonCount: { type: Number, default: 0 },
    hours: { type: Number, default: 0 },

    serial: { type: String, required: true, unique: true },
    issuedAt: { type: Date, default: Date.now },
  },
  { timestamps: true }
);

// One course certificate per student per course. `sparse` keeps samples
// (which have no courseId) out of the index entirely.
certificateSchema.index(
  { userId: 1, courseId: 1 },
  { unique: true, sparse: true, partialFilterExpression: { kind: 'course' } }
);

/** e.g. AA-2026-7F3C9B2A — short enough to read off a printed page. */
certificateSchema.statics.generateSerial = function generateSerial(prefix = 'AA') {
  const random = crypto.randomBytes(4).toString('hex').toUpperCase();
  return `${prefix}-${new Date().getFullYear()}-${random}`;
};

certificateSchema.set('toJSON', {
  transform(_doc, ret) {
    ret.id = ret._id;
    delete ret._id;
    delete ret.__v;
    return ret;
  },
});

module.exports = mongoose.model('Certificate', certificateSchema);
